import type { ButtonHTMLAttributes, ReactNode } from 'react'
import { Link, type LinkProps } from 'react-router-dom'

export type Status = 'within' | 'review' | 'large_deviation' | 'missing' | 'no_reference'

/** Small mono capitals: the atlas-plate label voice. */
export function Label({ children, className = '' }: { children: ReactNode; className?: string }) {
  return <span className={`font-mono text-[0.72rem] uppercase tracking-[0.16em] text-muted ${className}`}>{children}</span>
}

/** Figure or table caption: `FIG. 2  Deviation by level`. */
export function Caption({ label, children }: { label: string; children: ReactNode }) {
  return (
    <figcaption className="mt-3 flex gap-3 border-t border-rule pt-2 font-mono text-[0.72rem] uppercase tracking-[0.12em] text-muted">
      <span className="shrink-0 whitespace-nowrap text-text">{label}</span>
      <span>{children}</span>
    </figcaption>
  )
}

/** Hairline rule with an optional number and title, used between numbered sections. */
export function Rule({ number, title }: { number?: string; title?: string }) {
  return (
    <div className="flex items-baseline gap-4 border-t border-rule pt-3" role="presentation">
      {number && <span className="font-mono text-[0.72rem] tracking-[0.16em] text-accent">{number}</span>}
      {title && <span className="font-mono text-[0.72rem] uppercase tracking-[0.16em] text-muted">{title}</span>}
    </div>
  )
}

const STATUS_META: Record<Status, { glyph: string; word: string; color: string }> = {
  within: { glyph: '●', word: 'Within reference', color: 'text-within' },
  review: { glyph: '◐', word: 'Review', color: 'text-review' },
  large_deviation: { glyph: '▲', word: 'Larger deviation', color: 'text-large' },
  missing: { glyph: '○', word: 'Missing', color: 'text-missing' },
  no_reference: { glyph: '○', word: 'No reference', color: 'text-missing' },
}

export function statusWord(status: Status): string {
  return STATUS_META[status].word
}

/** Status is never colour alone: glyph, word and colour together. */
export function StatusBadge({ status, compact = false }: { status: Status; compact?: boolean }) {
  const meta = STATUS_META[status]
  return (
    <span className={`inline-flex items-center gap-1.5 font-mono text-[0.78rem] ${meta.color}`} data-status={status}>
      <span aria-hidden="true">{meta.glyph}</span>
      <span className={compact ? 'sr-only' : ''}>{meta.word}</span>
    </span>
  )
}

type ButtonProps = ButtonHTMLAttributes<HTMLButtonElement> & { variant?: 'primary' | 'secondary' | 'ghost' }

export function Button({ variant = 'primary', className = '', ...rest }: ButtonProps) {
  return <button type="button" className={`${BUTTON_BASE} ${BUTTON_STYLES[variant]} ${className}`} {...rest} />
}

const BUTTON_BASE = 'inline-flex items-center justify-center gap-2 rounded-sm px-5 py-2.5 font-mono text-[0.8rem] uppercase tracking-[0.14em] transition-colors disabled:cursor-not-allowed disabled:opacity-50'
const BUTTON_STYLES = {
  primary: 'bg-accent text-on-accent hover:opacity-90',
  secondary: 'border border-rule text-text hover:border-accent',
  ghost: 'text-muted hover:text-text',
}

/** A link that looks like a Button, so navigation stays a real anchor. */
export function ButtonLink({ variant = 'primary', className = '', ...rest }: LinkProps & { variant?: 'primary' | 'secondary' | 'ghost' }) {
  return <Link className={`${BUTTON_BASE} ${BUTTON_STYLES[variant]} ${className}`} {...rest} />
}

/** Tabular mono number, right-aligned, always with a unit (or a labelled ratio). */
export function NumberCell({ value, unit, digits = 2, signed = false }: { value: number | null | undefined; unit?: string; digits?: number; signed?: boolean }) {
  if (value === null || value === undefined || Number.isNaN(value)) return <span className="block text-right font-mono text-muted">—</span>
  const text = (signed && value > 0 ? '+' : '') + value.toFixed(digits)
  return (
    <span className="block text-right font-mono tabular-nums">
      {text}
      {unit && <span className="ml-1 text-[0.72rem] text-muted">{unit}</span>}
    </span>
  )
}

export function Panel({ children, className = '', as: Tag = 'section' }: { children: ReactNode; className?: string; as?: 'section' | 'div' | 'aside' }) {
  return <Tag className={`rounded-sm border border-rule bg-surface p-5 ${className}`}>{children}</Tag>
}

